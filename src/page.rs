//! The generated status page of podnet#500, PAGE-1 and PAGE-2.
//!
//! The page is a table of the repositories of a tree: the repository, its
//! version, its last commit and its state. It is generated from the tree,
//! never edited by hand. [`Page::check`] compares a page with the tree and names
//! each stale repository and field, so a page that drifts fails its gate.

use std::path::{Path, PathBuf};
use std::process::Command;

/// One row of the page.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Row {
    pub repository: String,
    pub version: String,
    pub commit: String,
    pub state: String,
}

/// The page, as rows and as text.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Page {
    pub root: PathBuf,
    pub rows: Vec<Row>,
}

/// A page entry that no longer matches the tree.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Stale {
    pub repository: String,
    pub field: &'static str,
    pub page: String,
    pub tree: String,
}

impl std::fmt::Display for Stale {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "the page is stale at {:?}: {} is {:?} on the page and {:?} in the tree",
            self.repository, self.field, self.page, self.tree
        )
    }
}

impl Page {
    /// Build the page of `root`: the root itself and each direct child
    /// directory that holds a `.git`.
    pub fn scan(root: &Path) -> anyhow::Result<Page> {
        let root = root
            .canonicalize()
            .map_err(|e| anyhow::anyhow!("{}: {e}", root.display()))?;
        let mut dirs = Vec::new();
        if root.join(".git").exists() {
            dirs.push(root.clone());
        }
        let mut children: Vec<PathBuf> = std::fs::read_dir(&root)
            .map_err(|e| anyhow::anyhow!("{}: {e}", root.display()))?
            .filter_map(|entry| entry.ok().map(|entry| entry.path()))
            .filter(|path| path.is_dir() && path.join(".git").exists())
            .collect();
        children.sort();
        dirs.extend(children);
        if dirs.is_empty() {
            anyhow::bail!(
                "{}: no git repository here, nor in a direct child directory",
                root.display()
            );
        }
        let rows = dirs
            .iter()
            .map(|dir| row_of(dir))
            .collect::<anyhow::Result<Vec<_>>>()?;
        let mut rows = rows;
        rows.sort_by(|a, b| a.repository.cmp(&b.repository));
        Ok(Page { root, rows })
    }

    /// The table alone.
    pub fn table(&self) -> String {
        let mut out = String::from("| repository | version | last commit | state |\n");
        out.push_str("| --- | --- | --- | --- |\n");
        for row in &self.rows {
            out.push_str(&format!(
                "| {} | {} | {} | {} |\n",
                row.repository, row.version, row.commit, row.state
            ));
        }
        out
    }

    /// The page: the table, under a line that says where it came from.
    pub fn render(&self) -> String {
        format!(
            "# Status\n\nGenerated by `podnet status --page` from `{}`.\n\n{}",
            self.root.display(),
            self.table()
        )
    }

    /// Each stale entry of `page`, compared with this tree.
    pub fn check(&self, page: &str) -> Vec<Stale> {
        let found = parse(page);
        let mut stale = Vec::new();
        for row in &self.rows {
            match found
                .iter()
                .find(|other| other.repository == row.repository)
            {
                None => stale.push(row.stale("repository", "absent", &row.repository)),
                Some(other) => {
                    for (field, page_value, tree_value) in [
                        ("version", &other.version, &row.version),
                        ("last commit", &other.commit, &row.commit),
                        ("state", &other.state, &row.state),
                    ] {
                        if page_value != tree_value {
                            stale.push(Stale {
                                repository: row.repository.clone(),
                                field,
                                page: page_value.clone(),
                                tree: tree_value.clone(),
                            });
                        }
                    }
                }
            }
        }
        for other in found {
            if !self
                .rows
                .iter()
                .any(|row| row.repository == other.repository)
            {
                stale.push(other.stale("repository", "present", "absent"));
            }
        }
        stale
    }
}

impl Row {
    fn stale(&self, field: &'static str, page: &str, tree: &str) -> Stale {
        Stale {
            repository: self.repository.clone(),
            field,
            page: page.to_string(),
            tree: tree.to_string(),
        }
    }
}

/// A row from the repository in `dir`.
fn row_of(dir: &Path) -> anyhow::Result<Row> {
    let repository = dir
        .file_name()
        .map(|name| name.to_string_lossy().into_owned())
        .unwrap_or_else(|| dir.display().to_string());
    let version = version_of(&dir.join("Cargo.toml")).unwrap_or_else(|| "-".into());
    let commit = git(dir, &["rev-parse", "--short=8", "HEAD"])
        .map(|text| text.trim().to_string())
        .unwrap_or_else(|| "-".into());
    let state = match git(dir, &["status", "--porcelain"]) {
        Some(text) => {
            let changed = text.lines().filter(|line| !line.trim().is_empty()).count();
            if changed == 0 {
                "clean".to_string()
            } else {
                format!("dirty ({changed})")
            }
        }
        None => "unknown".into(),
    };
    Ok(Row {
        repository,
        version,
        commit,
        state,
    })
}

fn version_of(manifest: &Path) -> Option<String> {
    let text = std::fs::read_to_string(manifest).ok()?;
    let value: toml::Value = toml::from_str(&text).ok()?;
    value
        .get("package")
        .and_then(|package| package.get("version"))
        .and_then(toml::Value::as_str)
        .map(str::to_string)
}

fn git(dir: &Path, args: &[&str]) -> Option<String> {
    let out = Command::new("git")
        .arg("-C")
        .arg(dir)
        .args(args)
        .env("GIT_PAGER", "cat")
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    Some(String::from_utf8_lossy(&out.stdout).into_owned())
}

/// The rows of a Markdown table: the cells of each `| ... |` line, with the
/// header and the separator skipped.
fn parse(page: &str) -> Vec<Row> {
    let mut rows = Vec::new();
    for line in page.lines() {
        let line = line.trim();
        if !line.starts_with('|') || !line.ends_with('|') {
            continue;
        }
        let cells: Vec<String> = line
            .trim_matches('|')
            .split('|')
            .map(|cell| cell.trim().trim_matches('`').trim().to_string())
            .collect();
        if cells.len() != 4 {
            continue;
        }
        if cells[0] == "repository" || cells.iter().all(|cell| cell.starts_with("---")) {
            continue;
        }
        rows.push(Row {
            repository: cells[0].clone(),
            version: cells[1].clone(),
            commit: cells[2].clone(),
            state: cells[3].clone(),
        });
    }
    rows
}

#[cfg(test)]
mod tests {
    use super::*;

    fn repo(root: &Path, name: &str) -> PathBuf {
        let dir = root.join(name);
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(
            dir.join("Cargo.toml"),
            format!("[package]\nname = \"{name}\"\nversion = \"0.1.0\"\n"),
        )
        .unwrap();
        let git = |args: &[&str]| {
            let out = Command::new("git")
                .arg("-C")
                .arg(&dir)
                .args(["-c", "user.name=test", "-c", "user.email=test@example"])
                .args(args)
                .output()
                .unwrap();
            assert!(out.status.success(), "{args:?}: {:?}", out);
        };
        git(&["init", "-q"]);
        git(&["add", "."]);
        git(&["commit", "-q", "-m", "init"]);
        dir
    }

    #[test]
    fn the_page_names_the_repository_version_commit_and_state() {
        let root = std::env::temp_dir().join(format!("podnet-page-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(&root).unwrap();
        repo(&root, "podnet");
        repo(&root, "podcrates");
        let page = Page::scan(&root).unwrap();
        assert_eq!(page.rows.len(), 2);
        assert_eq!(page.rows[0].repository, "podcrates");
        assert_eq!(page.rows[0].version, "0.1.0");
        assert_eq!(page.rows[0].state, "clean");
        assert_eq!(page.rows[0].commit.len(), 8);
        assert!(page.check(&page.render()).is_empty());
        let _ = std::fs::remove_dir_all(&root);
    }

    /// PAGE-2: a mutated page names the stale repository and the field.
    #[test]
    fn a_stale_version_fails_the_check() {
        let root = std::env::temp_dir().join(format!("podnet-page-stale-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(&root).unwrap();
        repo(&root, "podnet");
        let page = Page::scan(&root).unwrap();
        let text = page.render().replace("| 0.1.0 |", "| 9.9.9 |");
        let stale = page.check(&text);
        assert_eq!(stale.len(), 1, "{stale:?}");
        assert_eq!(stale[0].repository, "podnet");
        assert_eq!(stale[0].field, "version");
        assert!(stale[0].to_string().contains("9.9.9"), "{stale:?}");
        let _ = std::fs::remove_dir_all(&root);
    }

    #[test]
    fn a_missing_repository_is_named() {
        let root = std::env::temp_dir().join(format!("podnet-page-gone-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(&root).unwrap();
        repo(&root, "podnet");
        let page = Page::scan(&root).unwrap();
        let text = page
            .render()
            .lines()
            .filter(|line| !line.starts_with("| podnet "))
            .collect::<Vec<_>>()
            .join("\n");
        let stale = page.check(&text);
        assert_eq!(stale.len(), 1, "{stale:?}");
        assert_eq!(stale[0].field, "repository");
        let _ = std::fs::remove_dir_all(&root);
    }
}
